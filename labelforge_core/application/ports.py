"""Puertos que aislan los casos de uso de infraestructura concreta."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol

from labelforge_core.domain.run_record import RunRecord


class RunRepository(Protocol):
    def save(self, record: RunRecord) -> None: ...
    def get(self, run_id: str) -> RunRecord | None: ...
    def list(self) -> list[RunRecord]: ...
    def list_by_owner(self, user_id: int) -> list[RunRecord]: ...
    def find_by_output_file(self, output_file: str) -> RunRecord | None: ...
    def delete(self, run_id: str) -> bool: ...


@dataclass(frozen=True, slots=True)
class RunRuntimeSnapshot:
    running: bool
    stop_requested: bool
    pid: int | None
    exit_code: int | str | None
    last_error: str
    run_log_path: str | None
    seq: int
    lines: tuple[str, ...]
    log_entries: tuple[tuple[int, str], ...]


@dataclass(frozen=True, slots=True)
class StopRequest:
    accepted: bool
    process: Any | None = None


class RunSupervisor(Protocol):
    """Coordina de forma atomica el unico proceso local de etiquetado."""

    def claim_start(self) -> bool: ...
    def abort_start(self) -> None: ...
    def reset_for_run(self, log_path: str) -> None: ...
    def attach_process(self, process: Any) -> bool: ...
    def request_stop(self) -> StopRequest: ...
    def record_exit(self, exit_code: int) -> None: ...
    def record_error(self, public_message: str) -> None: ...
    def finish(self) -> bool: ...
    def append_log(self, line: str) -> None: ...
    def snapshot(self, since: int = 0) -> RunRuntimeSnapshot: ...
    def is_active(self) -> bool: ...
    def reset(self) -> None: ...
